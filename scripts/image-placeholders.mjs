/**
 * Generates data/placeholders.ts: a tiny blurred preview (data URL, ~10 px wide) for every Cloudinary
 * image referenced in data/. next/image paints it while the real image loads, so frames never show an
 * empty box. Run again after adding or replacing an image: `node scripts/image-placeholders.mjs`.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const UPLOAD = "https://res.cloudinary.com/daogrxxyw/image/upload/";
const dataDir = path.join(import.meta.dirname, "..", "data");

const urls = new Set();
for (const file of await readdir(dataDir)) {
  if (!file.endsWith(".ts") || file === "placeholders.ts") continue;
  const source = await readFile(path.join(dataDir, file), "utf8");
  for (const [url] of source.matchAll(/https:\/\/res\.cloudinary\.com\/daogrxxyw\/image\/upload\/[^"'\s]+/g)) urls.add(url);
}

const entries = [];
for (const url of [...urls].sort()) {
  const tiny = url.replace(UPLOAD, `${UPLOAD}w_12,c_limit,q_60,f_webp/`);
  const res = await fetch(tiny);
  if (!res.ok) throw new Error(`${res.status} for ${tiny}`);
  const base64 = Buffer.from(await res.arrayBuffer()).toString("base64");
  entries.push(`  ${JSON.stringify(url)}:\n    "data:image/webp;base64,${base64}",`);
}

const out = `// Generated by scripts/image-placeholders.mjs, do not edit by hand.\n\nexport const placeholders: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
await writeFile(path.join(dataDir, "placeholders.ts"), out);
console.log(`${entries.length} placeholders written to data/placeholders.ts`);
